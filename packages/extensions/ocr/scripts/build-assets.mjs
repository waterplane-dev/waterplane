#!/usr/bin/env node
/**
 * Copies the OCR engine into `packages/extensions/ocr/assets/` (gitignored) and writes its
 * `manifest.json` — the folder the host serves at `/api/plugin/ocr/asset/<file>` (manifest
 * `assets`) and the phone downloads when the person switches the extension on.
 *
 * From the lockfile's packages (root devDependencies, exact versions): tesseract.js's worker
 * script, tesseract.js-core's two LSTM-only cores with the wasm EMBEDDED (`*.wasm.js` — one file,
 * started from a blob URL, no second fetch), and the 4.0.0_best_int English and German data.
 * The manifest says each file's `bytes` and `sha256`; the phone refuses a download that does not
 * match, so a half-copied folder is never started.
 *
 * Run by `npm run build` (root). Missing packages stop it in words: a build without them would
 * ship an extension that can never be ready.
 */
import { createHash } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const ext = join(here, "..");
const root = join(ext, "../../..");
const out = join(ext, "assets");
const nm = join(root, "node_modules");

/** `role` is what the phone does with a file; `lang` names a language's data. */
const FILES = [
  { from: "tesseract.js/dist/worker.min.js", file: "worker.min.js", role: "worker" },
  { from: "tesseract.js-core/tesseract-core-simd-lstm.wasm.js", file: "tesseract-core-simd-lstm.wasm.js", role: "core-simd" },
  { from: "tesseract.js-core/tesseract-core-lstm.wasm.js", file: "tesseract-core-lstm.wasm.js", role: "core" },
  { from: "@tesseract.js-data/eng/4.0.0_best_int/eng.traineddata.gz", file: "eng.traineddata.gz", role: "lang", lang: "eng", name: "English" },
  { from: "@tesseract.js-data/deu/4.0.0_best_int/deu.traineddata.gz", file: "deu.traineddata.gz", role: "lang", lang: "deu", name: "German" },
];

const missing = FILES.filter((f) => !existsSync(join(nm, f.from)));
if (missing.length) {
  console.error(`ocr assets: ${missing.map((f) => f.from).join(", ")} not installed — run \`npm ci\` at the repo root (they are root devDependencies).`);
  process.exit(1);
}

const version = (p) => JSON.parse(readFileSync(join(nm, p, "package.json"), "utf8")).version;
mkdirSync(out, { recursive: true });
const keep = new Set(["manifest.json", ...FILES.map((f) => f.file)]);
for (const name of readdirSync(out)) if (!keep.has(name)) rmSync(join(out, name), { recursive: true, force: true });

const files = FILES.map(({ from, ...f }) => {
  const src = join(nm, from);
  const dst = join(out, f.file);
  const s = statSync(src);
  if (!existsSync(dst) || statSync(dst).size !== s.size || statSync(dst).mtimeMs < s.mtimeMs) copyFileSync(src, dst);
  const buf = readFileSync(dst);
  return { ...f, bytes: buf.length, sha256: createHash("sha256").update(buf).digest("hex") };
});
const manifest = {
  "//": "Generated by packages/extensions/ocr/scripts/build-assets.mjs — do not edit.",
  format: 1,
  engine: { "tesseract.js": version("tesseract.js"), "tesseract.js-core": version("tesseract.js-core") },
  files,
};
const text = JSON.stringify(manifest, null, 2) + "\n";
const mf = join(out, "manifest.json");
if (!existsSync(mf) || readFileSync(mf, "utf8") !== text) writeFileSync(mf, text);
const mb = (files.reduce((n, f) => n + f.bytes, 0) / 1e6).toFixed(1);
console.log(`ocr assets: ${files.length} files, ${mb} MB in packages/extensions/ocr/assets`);
