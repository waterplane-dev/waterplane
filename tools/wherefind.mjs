/**
 * The README's "Where do I find" table, generated from the door registry
 * (`packages/web/src/doors/`, whole-app journey spec D10): task, the control to tap, the screen it
 * opens, taps from Home. `node tools/wherefind.mjs --write` rewrites the block between the
 * `where-find` markers in README.md; `tools/wherefind.test.mjs` fails when the README differs.
 * Run straight from TypeScript (node --experimental-strip-types), like tools/appdoors.test.mjs.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
export const README = join(ROOT, "README.md");
export const START = "<!-- where-find:start (generated by tools/wherefind.mjs; do not edit by hand) -->";
export const END = "<!-- where-find:end -->";

const FROM = {
  home: "Home", "home menu": "Home ☰ menu", "repo row": "a repo row", "repo menu": "a repo row's More",
  "status strip": "the status strip", "session header": "the session header", "toolbar menu": "the session ☰ menu",
  composer: "above the prompt bar", "send menu": "Send's arrow", settings: "Settings", search: "Settings search",
  notification: "a notification", welcome: "Welcome",
};
const from = (f) => (FROM[f] ?? (f === "sheet:hosts" ? "the Desktops screen" : f.startsWith("sheet:") ? "the " + f.slice(6) + " screen" : f));
const cell = (s) => String(s).replace(/[\\|]/g, "\\$&");

/** The table's lines for a door list: one row per task, doors fewest-taps first. */
export function table(doors) {
  const byTask = new Map();
  for (const d of doors) if (d.task) (byTask.get(d.task) ?? byTask.set(d.task, []).get(d.task)).push(d);
  const rows = [...byTask.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([task, ds]) => {
    ds.sort((a, b) => (a.taps ?? 99) - (b.taps ?? 99) || a.label.localeCompare(b.label));
    const seen = new Set();
    const ways = ds.filter((d) => { const k = d.from + "|" + d.label + "|" + d.title + "|" + (d.tab ?? ""); return !seen.has(k) && seen.add(k); });
    const how = ways.map((d) => `${from(d.from)} › **${d.label}**`).join("; or ");
    const opens = [...new Set(ways.map((d) => d.title + (d.tab ? ` › ${d.tab}` : "")))].join("; ");
    const taps = ways.find((d) => d.taps != null)?.taps;
    return `| ${cell(task)} | ${cell(how)} | ${cell(opens)} | ${taps ?? "-"} |`;
  });
  return ["| I want to | Tap | It opens | Taps from Home |", "|---|---|---|---|", ...rows].join("\n");
}

export async function generated() {
  const { DOORS } = await import(join(ROOT, "packages/web/src/doors/index.ts"));
  return `${START}\n${table(DOORS)}\n${END}`;
}

export function current(src = readFileSync(README, "utf8")) {
  const a = src.indexOf(START), b = src.indexOf(END);
  return a < 0 || b < 0 ? null : src.slice(a, b + END.length);
}

if (process.argv[1] === new URL(import.meta.url).pathname && process.argv.includes("--write")) {
  const src = readFileSync(README, "utf8");
  const cur = current(src);
  if (!cur) throw new Error("README.md has no where-find markers");
  const next = await generated();
  writeFileSync(README, src.split(cur).join(next));
  console.log("README.md table written");
}
